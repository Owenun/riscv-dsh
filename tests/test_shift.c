/* tests/test_shift.c —— Task 6：移位指令边界专项（SLLI/SRLI/SRAI/SLL/SRL/SRA）。
   重点：0x8000000000000000 边界（SRLI/SRL 63 →1，SRAI/SRA 63 →全 1 符号回填，
   SRA 1/2 →0xC000..0/0xE000..0）、移位量取低 6 位（寄存器形式 65≡1、66≡2）、
   移位量 0。
   寄存器移位量取 rs2 低 6 位（RISC-V 规范；设计文档 §4.2 写作 rs1 系笔误）。 */
#include "harness.h"
#include "enc.h"

int main(void)
{
    /* ---- 立即数移位（shamt=imm[5:0]，decode 保证 imm[11:6] 合法） ---- */
    one(ENC_I(0, 10, 1, 12, 0x13), 0x0123456789ABCDEFULL, 0, 0x0123456789ABCDEFULL, 12); /* SLLI 0 不变 */
    one(ENC_I(63, 10, 1, 12, 0x13), 1, 0, (uint64_t)0x8000000000000000ULL, 12); /* SLLI 63 →最高位 */
    one(ENC_I(1, 10, 1, 12, 0x13), (uint64_t)0x8000000000000000ULL, 0, 0, 12);  /* SLLI 1 移出 →0 */
    one(ENC_I(63, 10, 5, 12, 0x13), (uint64_t)0x8000000000000000ULL, 0, 1, 12); /* SRLI 63 →1（仅剩 bit0） */
    one(ENC_I(1, 10, 5, 12, 0x13), (uint64_t)0x8000000000000000ULL, 0, 0x4000000000000000ULL, 12); /* SRLI 1 */
    one(ENC_I(60, 10, 5, 12, 0x13), (uint64_t)-1, 0, 0xF, 12);                  /* SRLI 60 全 1 →0xF */
    one(ENC_I(0x43F, 10, 5, 12, 0x13), (uint64_t)0x8000000000000000ULL, 0, (uint64_t)-1, 12); /* SRAI 63: -2^63>>63=-1 */
    one(ENC_I(0x401, 10, 5, 12, 0x13), (uint64_t)0x8000000000000000ULL, 0, (uint64_t)0xC000000000000000ULL, 12); /* SRAI 1 符号回填 */
    one(ENC_I(0x404, 10, 5, 12, 0x13), (uint64_t)-1, 0, (uint64_t)-1, 12);      /* SRAI 4: -1 保持 -1 */
    one(ENC_I(0x402, 10, 5, 12, 0x13), (uint64_t)-16, 0, (uint64_t)-4, 12);     /* SRAI 2 负数 */

    /* ---- 寄存器移位（移位量 = x[rs2] 低 6 位） ---- */
    one(OP_STD(0x00, 11, 10, 1, 12, 0x33), 1, 65, 2, 12);                       /* SLL: 65≡1 */
    one(OP_STD(0x00, 11, 10, 1, 12, 0x33), (uint64_t)0x8000000000000000ULL, 63, 0, 12); /* SLL 63 移出 →0 */
    one(OP_STD(0x00, 11, 10, 1, 12, 0x33), 1, 0, 1, 12);                        /* SLL 0 不变 */
    one(OP_STD(0x00, 11, 10, 5, 12, 0x33), (uint64_t)0x8000000000000000ULL, 63, 1, 12); /* SRL 63 →1 */
    one(OP_STD(0x00, 11, 10, 5, 12, 0x33), (uint64_t)0x8000000000000000ULL, 65, (uint64_t)0x4000000000000000ULL, 12); /* SRL: 65≡1 */
    one(OP_STD(0x20, 11, 10, 5, 12, 0x33), (uint64_t)0x8000000000000000ULL, 63, (uint64_t)-1, 12); /* SRA 63: -2^63>>63=-1 */
    one(OP_STD(0x20, 11, 10, 5, 12, 0x33), (uint64_t)0x8000000000000000ULL, 66, (uint64_t)0xE000000000000000ULL, 12); /* SRA: 66≡2 符号回填 */
    one(OP_STD(0x20, 11, 10, 5, 12, 0x33), (uint64_t)-1, 65, (uint64_t)-1, 12); /* SRA: 65≡1, -1 保持 -1 */

    TEST_DONE();
}
